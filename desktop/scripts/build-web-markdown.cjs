// 从锁定的依赖生成 Web 页面唯一使用的浏览器包，并保留依赖许可证。
const fs = require('node:fs')
const path = require('node:path')
const esbuild = require('esbuild')
const desktop = path.resolve(__dirname, '..')
const target = path.resolve(desktop, '../channel/web/static/vendor/markdown-it')

function buildWebMarkdown() {
  const lock = JSON.parse(fs.readFileSync(path.join(desktop, 'package-lock.json')))
  for (const [name, version] of [['markdown-it', '14.2.0'], ['linkify-it', '5.0.2']]) {
    const installed = JSON.parse(fs.readFileSync(path.join(desktop, 'node_modules', name, 'package.json')))
    const locked = lock.packages[`node_modules/${name}`]
    if (installed.version !== version || locked.version !== version) throw new Error(`Unexpected ${name} version`)
  }
  const result = esbuild.buildSync({
    absWorkingDir: desktop,
    stdin: { contents: 'module.exports = require("markdown-it");', resolveDir: desktop, sourcefile: 'web-markdown-entry.cjs' },
    bundle: true, platform: 'browser', format: 'iife', globalName: 'markdownit',
    target: 'es2020', minify: true, write: false, metafile: true, legalComments: 'inline',
    banner: { js: '/*! markdown-it 14.2.0 + linkify-it 5.0.2; MIT; see LICENSES.txt. Generated by desktop/scripts/build-web-markdown.cjs. */' },
  })
  const packages = [...new Set(Object.keys(result.metafile.inputs).map(input =>
    input.replaceAll('\\', '/').match(/node_modules\/([^/]+)\//)?.[1]).filter(Boolean))].sort()
  const licenses = packages.map(name => {
    const directory = path.join(desktop, 'node_modules', name)
    const metadata = JSON.parse(fs.readFileSync(path.join(directory, 'package.json')))
    if (lock.packages[`node_modules/${name}`]?.version !== metadata.version) throw new Error(`Unlocked bundled dependency: ${name}`)
    const license = ['LICENSE', 'LICENSE.txt', 'LICENSE-MIT.txt', 'LICENSE-MIT'].find(file => fs.existsSync(path.join(directory, file)))
    if (!license) throw new Error(`License not found: ${name}`)
    return `${name} ${metadata.version}\n${metadata.license}\n${fs.readFileSync(path.join(directory, license), 'utf8').trim()}\n`
  }).join('\n---\n\n')
  return { 'markdown-it.min.js': result.outputFiles[0].text, 'LICENSES.txt': licenses }
}

if (require.main === module) {
  for (const [name, content] of Object.entries(buildWebMarkdown())) {
    const file = path.join(target, name)
    if (process.argv.includes('--check')) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) throw new Error(`Stale Web asset: ${name}`)
    } else fs.writeFileSync(file, content)
  }
}
module.exports = { buildWebMarkdown }
